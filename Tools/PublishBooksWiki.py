"""Publish the four public book manuscripts after the central P4/Git mirror."""
import argparse
import json
import os
from pathlib import Path
import posixpath
import re
import subprocess
import tempfile
from urllib.parse import quote, unquote, urlsplit


SOURCE = 'https://github.com/sgua83/Blink.git'
WIKI = 'https://github.com/sgua83/Blink.wiki.git'
WEB = 'https://github.com/sgua83/Blink'
BOOKS = (
    ('并行编程的艺术', 'Book-Parallel-Programming', 'The Art of Parallel Programming', '并行编程的艺术-B语言'),
    ('Blink和Rust混合编程', 'Book-Blink-and-Rust', 'Blink and Rust Mixed Programming', 'Blink和Rust混合编程'),
    ('B语言源码分析', 'Book-B-Source-Analysis', 'B Language Source Analysis', 'B语言源码分析'),
    ('BLEngine源码分析', 'Book-BLEngine-Source-Analysis', 'BLEngine Source Analysis', 'BLEngine源码分析'),
)
GENERATED = '<!-- Generated by Blink Tools/PublishBooksWiki.py; edit the P4 book source. -->'
BEGIN = '<!-- BEGIN Blink books navigation -->'
END = '<!-- END Blink books navigation -->'
PRIVATE = {'Docs/Issues.md', 'Docs/FixedIssues.md'}


def git(repo, *args, data=None, env=None):
    process_env = dict(os.environ, GIT_TERMINAL_PROMPT='0', GCM_INTERACTIVE='Never')
    if env:
        process_env.update(env)
    result = subprocess.run(['git', '--git-dir', str(repo), *args], input=data,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=process_env)
    if result.returncode:
        raise RuntimeError(result.stderr.decode('utf-8', errors='replace').strip())
    return result.stdout


def text(repo, *args):
    return git(repo, *args).decode('utf-8').strip()


def repo_url(sha, path, image=False):
    if image:
        return f'https://raw.githubusercontent.com/sgua83/Blink/{sha}/{quote(path)}'
    return f'{WEB}/blob/{sha}/{quote(path)}'


def rewrite_book(body, source, sha, files):
    """Change Markdown destinations, leaving prose, fenced and inline code intact."""
    book_pages = {f'sample/{book[0]}.md': book[1] for book in BOOKS}
    counts = {'images': 0, 'links': 0, 'private_references': 0}

    def destination(value, image=False):
        url = urlsplit(value)
        if url.scheme or url.netloc or not url.path:
            return value
        path = posixpath.normpath(posixpath.join(posixpath.dirname(source), unquote(url.path)))
        if path in PRIVATE:
            return None
        if path not in files:
            raise RuntimeError(f'Book reference is absent from the public snapshot: {source}: {value}')
        counts['images' if image else 'links'] += 1
        if path in book_pages and not image:
            target = f'{WEB}/wiki/{book_pages[path]}'
        else:
            target = repo_url(sha, path, image)
        if url.query:
            target += '?' + url.query
        if url.fragment:
            target += '#' + url.fragment
        return target

    def markdown(match):
        image, label, value, title = match.groups()
        target = destination(value, bool(image))
        if target is None:
            counts['private_references'] += 1
            return f'{label}（内部 P4 台账，不公开；[公开反馈]({WEB}/issues)）'
        return f'{image}[{label}]({target}{title or ""})'

    def segment(value):
        value = re.sub(r'(!?)\[([^\]\n]*)\]\(<?([^\s)>]+)>?(\s+["\'][^\n]*?["\'])?\)', markdown, value)
        # Reference-style links and HTML are handled outside code, too.
        def reference(match):
            target = destination(match[2])
            if target is None:
                raise RuntimeError('Private reference-style destination must be removed from the public book source.')
            return match[1] + target + match[3]
        value = re.sub(r'(?m)^(\s*\[[^\]\n]+\]:\s*)<?([^\s>]+)>?(.*)$', reference, value)
        def html(match):
            target = destination(match[3], match[1].lower() == 'src')
            if target is None:
                raise RuntimeError('Private HTML destination must be removed from the public book source.')
            return match[1] + '=' + match[2] + target + match[2]
        return re.sub(r'\b(href|src)=(["\'])(.*?)\2', html, value)

    output = []
    fence = None
    for line in body.splitlines(keepends=True):
        marker = re.match(r'^ {0,3}(`{3,}|~{3,})', line)
        if marker:
            run = marker[1]
            if fence is None:
                fence = run
            elif run[0] == fence[0] and len(run) >= len(fence):
                fence = None
            output.append(line)
        elif fence:
            output.append(line)
        else:
            pieces = re.split(r'(`+[^`\n]*`+)', line)
            output.append(''.join(piece if piece.startswith('`') else segment(piece) for piece in pieces))
    return ''.join(output), counts


def navigation(original):
    block = f'''{BEGIN}
## B 语言书籍 / Blink books

[中文书籍目录]({WEB}/wiki/Blink-Books) · [English book index]({WEB}/wiki/Blink-Books-English)

四本书的完整 Markdown 阅读页由 P4 → GitHub main → Wiki 自动同步。版本与 PDF 下载见书籍目录。
Full Markdown manuscripts are synchronized from the public main snapshot. See the index for versions and PDFs.
{END}'''
    if BEGIN in original or END in original:
        if original.count(BEGIN) != 1 or original.count(END) != 1 or original.index(BEGIN) > original.index(END):
            raise RuntimeError('Wiki navigation markers were edited; preserve the user page and resolve the block first.')
        return original[:original.index(BEGIN)] + block + original[original.index(END) + len(END):]
    return original + ('\n' if original.endswith('\n') else '\n\n') + block + '\n'


def build_pages(source, sha, files):
    version = text(source, 'show', f'{sha}:VERSION')
    message = text(source, 'log', '-1', '--format=%B', sha)
    change = re.search(r'^P4-Change: (\d+)$', message, re.M)
    if not change or not re.search(r'^P4-Depot: //BLanguage/main/$', message, re.M):
        raise RuntimeError('Public main must identify its authoritative P4 snapshot.')
    provenance = f'main · VERSION {version} · P4 CL {change[1]} · Git [`{sha[:12]}`]({WEB}/tree/{sha})'
    pages, coverage = {}, []
    for title, page, english, pdf in BOOKS:
        path = f'sample/{title}.md'
        original = git(source, 'show', f'{sha}:{path}').decode('utf-8')
        body, counts = rewrite_book(original, path, sha, files)
        header = f'''{GENERATED}
[中文目录]({WEB}/wiki/Blink-Books) · [English index]({WEB}/wiki/Blink-Books-English) · [原始书稿]({repo_url(sha, path)})

> 开发版书稿 / Development manuscript — {provenance}。
> 适用能力以本书及对应源码为准；正式发行请使用 [Releases]({WEB}/releases/latest) 的版本与随包文档。BLEngine 书稿中的案例不表示引擎已开源。

'''
        pages[page + '.md'] = header + body
        coverage.append(dict(source=path, page=page, source_bytes=len(original.encode()), **counts))
    for language in ('zh', 'en'):
        english = language == 'en'
        heading = 'Blink books' if english else 'B 语言书籍'
        intro = ('These are the four complete Chinese manuscripts, with English navigation. '
                 'This Wiki follows development main, not a released SDK. '
                 'Use the matching release and its bundled documentation for a formal release.' if english else
                 '这里提供四本中文书的完整 Markdown 正文。本 Wiki 跟随开发版 main，不等同于正式发行 SDK；使用正式版时，请以对应发行包及随包文档为准。')
        lines = [GENERATED, f'# {heading}', '',
                 f'[中文目录]({WEB}/wiki/Blink-Books) · [English index]({WEB}/wiki/Blink-Books-English)', '', intro, '',
                 f'> {provenance}', '',
                 f'[正式版下载 / Releases]({WEB}/releases/latest) · [公开反馈 / Issues]({WEB}/issues) · [Discussions]({WEB}/discussions)', '',
                 '| Book / 书籍 | Markdown | PDF |', '|---|---|---|']
        for title, page, translated, pdf in BOOKS:
            standard = f'sample/pdf/{pdf}.pdf'
            mobile = f'sample/pdf/{pdf}-手机阅读版.pdf'
            for path in (standard, mobile):
                if path not in files:
                    raise RuntimeError(f'Public PDF is absent: {path}')
            name = f'{translated}<br>{title}' if english else title
            lines.append(f'| {name} | [阅读 / Read]({WEB}/wiki/{page}) | [标准版]({repo_url(sha, standard)}) · [手机版]({repo_url(sha, mobile)}) |')
        lines += ['', ('PDF links refer to the existing products in this repository snapshot; PDFs are rebuilt separately from Markdown. '
                       'BLEngine is an independent consumer; its book does not claim the engine is open source.' if english else
                       'PDF 链接指向该仓库快照内已有成品，PDF 与 Markdown 分别重建。BLEngine 是独立消费者，书稿不表示引擎已开源。'), '',
                  ('The central GUA tasks run at 09:00 and 21:00 Beijing time. After the existing mirror/release action, '
                   'book sync reads public main and updates only these books and marked navigation. '
                   'User content outside marked blocks is retained. Edit manuscripts in P4; generated reading pages are replaced on sync.' if english else
                   'GUA 现有中央任务于北京时间 09:00、21:00 启动，在原源码镜像／发行步骤结束后同步书籍。同步只读取已公开 main，管理这四本书及标记导航；标记区块之外的用户内容保留。请在 P4 修改书稿，生成阅读页会在下次同步时重新生成。'), '']
        pages['Blink-Books-English.md' if english else 'Blink-Books.md'] = '\n'.join(lines)
    return pages, coverage


def publish(source, wiki):
    if text(source, 'config', '--get', 'remote.origin.url') != SOURCE:
        raise RuntimeError('Source origin must be the authorized sgua83/Blink repository.')
    public_head = text(source, 'ls-remote', 'origin', 'refs/heads/main').split()[0]
    # Read only an actual public commit. The source publisher owns source fetches.
    # Git history supplies the last book/resource snapshot; unrelated code changes
    # do not create four identical book revisions or a second publication state.
    inputs = [f'sample/{book[0]}.md' for book in BOOKS] + [
        'sample/figures/', 'sample/pdf/', 'sample/BLEngine摘录来源.md',
        'sample/hybrid/BLEngine摘录来源.md', 'Docs/BLanguage.md', 'Docs/Architecture.md']
    sha = text(source, 'log', '-1', '--format=%H', public_head, '--', *inputs)
    if not sha:
        raise RuntimeError('Public main has no book snapshot.')
    files = set(git(source, 'ls-tree', '-r', '-z', '--name-only', sha).decode('utf-8').split('\0'))
    pages, coverage = build_pages(source, sha, files)
    wiki.mkdir(parents=True, exist_ok=True)
    if not (wiki / 'config').exists():
        git(wiki, 'init', '--bare', str(wiki))
        git(wiki, 'remote', 'add', 'origin', WIKI)
    if text(wiki, 'config', '--get', 'remote.origin.url') != WIKI:
        raise RuntimeError('Wiki origin must be the authorized sgua83/Blink Wiki.')
    remote = text(wiki, 'ls-remote', '--symref', 'origin', 'HEAD')
    branch = re.search(r'^ref: (refs/heads/[^\s]+)\s+HEAD$', remote, re.M)
    if not branch:
        raise RuntimeError('Initialize the Wiki in GitHub before publishing books.')
    branch = branch[1]
    git(wiki, 'fetch', '--no-tags', 'origin', branch)
    head = text(wiki, 'rev-parse', 'FETCH_HEAD')
    existing = set(git(wiki, 'ls-tree', '-r', '-z', '--name-only', head).decode('utf-8').split('\0'))
    for page in pages:
        if page in existing and not git(wiki, 'show', f'{head}:{page}').decode('utf-8').startswith(GENERATED):
            raise RuntimeError(f'Existing user page will not be replaced: {page}')
    for page in ('Home.md', 'B语言书籍.md', '_Sidebar.md'):
        original = git(wiki, 'show', f'{head}:{page}').decode('utf-8') if page in existing else ''
        # Home and the user's book page are never created or wholly regenerated.
        if page in existing or page == '_Sidebar.md':
            pages[page] = navigation(original)
    with tempfile.TemporaryDirectory(prefix='books-', dir=wiki) as run:
        index_env = {'GIT_INDEX_FILE': str(Path(run) / 'index')}
        git(wiki, 'read-tree', head, env=index_env)
        for path, body in pages.items():
            blob = git(wiki, 'hash-object', '-w', '--stdin', data=body.encode('utf-8')).decode().strip()
            git(wiki, 'update-index', '--add', '--cacheinfo', f'100644,{blob},{path}', env=index_env)
        tree = git(wiki, 'write-tree', env=index_env).decode().strip()
    if tree == text(wiki, 'rev-parse', head + '^{tree}'):
        result = dict(status='WIKI_UNCHANGED', source=sha, wiki=head, coverage=coverage)
    else:
        identity = ['-c', 'user.name=Blink book mirror', '-c', 'user.email=sgua83@users.noreply.github.com']
        commit = git(wiki, *identity, 'commit-tree', tree, '-p', head,
                     data=f'Sync public B book manuscripts\n\nSource-Git: {sha}\n'.encode()).decode().strip()
        git(wiki, 'push', 'origin', f'{commit}:{branch}')
        confirmed = text(wiki, 'ls-remote', 'origin', branch).split()[0]
        if confirmed != commit:
            raise RuntimeError(f'Wiki push needs inspection: remote is {confirmed}, proposed {commit}')
        result = dict(status='WIKI_PUBLISHED', source=sha, wiki=commit, coverage=coverage)
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    root = Path(__file__).resolve().parent.parent
    parser.add_argument('--source-mirror', type=Path, default=root / 'Saved/GitPublish/Mirror.git')
    parser.add_argument('--wiki-mirror', type=Path, default=root / 'Saved/GitPublish/Wiki.git')
    args = parser.parse_args()
    args.wiki_mirror = args.wiki_mirror.resolve()
    args.wiki_mirror.mkdir(parents=True, exist_ok=True)
    try:
        result = publish(args.source_mirror.resolve(), args.wiki_mirror)
    except Exception as error:
        result = dict(status='WIKI_FAILED', error=str(error))
    output = json.dumps(result, ensure_ascii=False)
    with (args.wiki_mirror / 'publish-books.log').open('a', encoding='utf-8', newline='\n') as log:
        log.write(output + '\n')
    print(output, flush=True)
    raise SystemExit(1 if result['status'] == 'WIKI_FAILED' else 0)
