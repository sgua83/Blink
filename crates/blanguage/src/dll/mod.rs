//! Windows x64 DLL 输出；同一接口同时生成 C/C++ 头文件与 Rust 安全包装器。
mod source;
use crate::{
    ExecutableProgram,
    ir::{Scalar, Ty, align_up},
};
pub(crate) use source::application_source;
use std::{fmt::Write, path::Path};
type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

fn identifier(value: &str) -> Result<String> {
    if value.is_empty()
        || !value
            .bytes()
            .enumerate()
            .all(|(i, c)| c.is_ascii_alphabetic() || c == b'_' || (i != 0 && c.is_ascii_digit()))
    {
        return Err(format!("DLL 接口标识符需要 ASCII 字母、数字和下划线：{value}").into());
    }
    Ok(value.into())
}
fn constant_name(name: &str) -> String {
    let mut out = String::new();
    let hex = b"0123456789ABCDEF";
    for byte in name.bytes() {
        match byte {
            b'a'..=b'y' => out.push(byte.to_ascii_uppercase() as char),
            b'0'..=b'9' => out.push(byte as char),
            byte => {
                out.push('Z');
                out.push(hex[(byte >> 4) as usize] as char);
                out.push(hex[(byte & 15) as usize] as char);
            }
        }
    }
    out
}
fn plain(ty: &Ty) -> bool {
    !ty.owns_resources()
        && ty.view.is_none()
        && ty.fields.iter().all(|(_, _, t)| plain(t))
        && ty.array.as_ref().is_none_or(|t| plain(t))
}
fn scalar(s: Scalar) -> (&'static str, &'static str) {
    match s {
        Scalar::F32 => ("float", "f32"),
        Scalar::I32 => ("int32_t", "i32"),
        Scalar::U32 | Scalar::Bool => ("uint32_t", "u32"),
    }
}
fn fields(ty: &Ty, name: &str, base: u32, out: &mut Vec<(String, Scalar, u32)>) -> Result<()> {
    if !ty.fields.is_empty() {
        for (n, offset, t) in &ty.fields {
            let field = identifier(n)?.replace('z', "z7a").replace('_', "z5f");
            fields(
                t,
                &format!("{name}_f{}_{field}", n.len()),
                base + offset,
                out,
            )?;
        }
    } else if let Some(t) = &ty.array {
        for i in 0..ty.values[0] {
            fields(
                t,
                &format!("{name}_{i}"),
                base + i * align_up(t.size, t.align),
                out,
            )?;
        }
    } else {
        for (i, &(s, offset)) in ty.components.iter().enumerate() {
            let n = if ty.result {
                if i == 0 {
                    format!("{name}_tag")
                } else {
                    format!("{name}_payload_{}", i - 1)
                }
            } else if ty.components.len() == 1 {
                name.into()
            } else {
                format!("{name}_{}", ["x", "y", "z", "w"][i])
            };
            out.push((n, s, base + offset));
        }
    }
    Ok(())
}
fn layout(name: &str, ty: &Ty, c: &mut String, r: &mut String) -> Result<()> {
    if ty.components.len() == 1 && ty.size == 4 && ty.align == 4 && ty.fields.is_empty() {
        let (ct, rt) = scalar(ty.components[0].0);
        writeln!(c, "typedef {ct} {name};")?;
        writeln!(r, "pub type {name} = {rt};")?;
        return Ok(());
    }
    writeln!(
        c,
        "typedef struct __declspec(align({})) {name} {{",
        ty.align
    )?;
    writeln!(
        r,
        "#[repr(C, align({}))]\n#[derive(Clone, Copy, Default)]\npub struct {name} {{",
        ty.align
    )?;
    let mut members = Vec::new();
    fields(ty, "v", 0, &mut members)?;
    let mut end = 0;
    for (n, s, offset) in members {
        if offset > end {
            writeln!(c, "    uint8_t pad_{end}[{}];", offset - end)?;
            writeln!(r, "    pub pad_{end}: [u8; {}],", offset - end)?;
        }
        let (ct, rt) = scalar(s);
        writeln!(c, "    {ct} {n}; /* byte {offset} */")?;
        writeln!(r, "    pub {n}: {rt}, // byte {offset}")?;
        end = offset + 4;
    }
    let size = align_up(ty.size, ty.align);
    if size > end {
        writeln!(c, "    uint8_t pad_{end}[{}];", size - end)?;
        writeln!(r, "    pub pad_{end}: [u8; {}],", size - end)?;
    }
    writeln!(c, "}} {name};")?;
    writeln!(r, "}}")?;
    Ok(())
}

fn generate(p: &ExecutableProgram, prefix: &str) -> Result<(String, String, String)> {
    if !p.accelerations().is_empty()
        || !p.textures().is_empty()
        || p.buffers().iter().any(|b| !plain(&b.ty))
        || p.uniforms().iter().any(|u| !plain(&u.ty))
    {
        return Err("DLL 数据接口目前支持纯值 dataset 与 uniform；view、纹理和加速结构需要原生 Rust 资源 API".into());
    }
    let upper = constant_name(prefix);
    let mut c = format!(
        "/* Generated by blc. Windows x64 C ABI. Do not edit. */\n#ifndef {upper}_BLINK_H\n#define {upper}_BLINK_H\n#include <stdint.h>\n#include <stddef.h>\n"
    );
    let mut types = String::from("// Generated by blc. Do not edit.\n");
    let mut cp = Vec::new();
    let mut rp = Vec::new();
    let mut args = Vec::new();
    let mut safe_r = Vec::new();
    let mut safe_args = Vec::new();
    let mut buffers = Vec::new();
    let mut values = String::from("let mut values = Vec::new();\n");
    for b in p.buffers() {
        let n = identifier(&b.name)?;
        let t = format!("{prefix}_data_{n}");
        layout(&t, &b.ty, &mut c, &mut types)?;
        if let Some(count) = b.count {
            writeln!(
                c,
                "#define {upper}_{}_COUNT {count}u",
                constant_name(&n)
            )?;
            writeln!(
                types,
                "pub const {}_COUNT: usize = {count};",
                constant_name(&n)
            )?;
        }
        let write = b.access.writes();
        let ct = if write { "" } else { "const " };
        let rt = if write { "mut" } else { "const" };
        cp.push(format!("{ct}{t} *data_{n}"));
        cp.push(format!("uint32_t count_{n}"));
        rp.push(format!("data_{n}: *{rt} {t}"));
        rp.push(format!("count_{n}: u32"));
        args.push(format!("data_{n}"));
        args.push(format!("count_{n}"));
        safe_r.push(format!(
            "data_{n}: &{}[{t}]",
            if write { "mut " } else { "" }
        ));
        safe_args.push(format!(
            "data_{n}.{}()",
            if write { "as_mut_ptr" } else { "as_ptr" }
        ));
        safe_args.push(format!(
            "u32::try_from(data_{n}.len()).map_err(|e| e.to_string())?"
        ));
        buffers.push(
            format!("FfiBuffer {{data: data_{n}.cast_mut().cast(), count: count_{n}}}")
                .replace(".cast_mut()", if write { "" } else { ".cast_mut()" }),
        );
    }
    for (i, u) in p.uniforms().iter().enumerate() {
        let n = identifier(&u.name)?;
        let t = format!("{prefix}_uniform_{n}");
        layout(&t, &u.ty, &mut c, &mut types)?;
        cp.push(format!("const {t} *param_{n}"));
        rp.push(format!("param_{n}: *const {t}"));
        args.push(format!("param_{n}"));
        safe_r.push(format!("param_{n}: &{t}"));
        safe_args.push(format!("param_{n}"));
        writeln!(
            values,
            "if param_{n}.is_null() {{ return Err(std::io::Error::other(\"null uniform: {n}\").into()); }}\nvalues.extend(unsafe {{ blcompute::ffi::uniform_values(param_{n}.cast(), &handle.program().uniforms()[{i}].ty) }});"
        )?;
    }
    let c_run = cp.join(", ");
    let r_run = rp.join(", ");
    let comma = if cp.is_empty() { "" } else { ", " };
    let replacements = [
        ("@PREFIX@", prefix.to_owned()),
        ("@COMMA@", comma.to_owned()),
        ("@C_PARAMS@", c_run),
        ("@R_PARAMS@", r_run),
        ("@ARGS@", args.join(", ")),
        ("@SAFE_PARAMS@", safe_r.join(", ")),
        ("@SAFE_ARGS@", safe_args.join(", ")),
        ("@TYPES@", types),
        ("@CREATE@", source::constructor(p)?),
        ("@VALUES@", values),
        ("@BUFFERS@", buffers.join(", ")),
    ];
    let render = |template: &str| {
        replacements
            .iter()
            .fold(template.to_owned(), |text, (key, value)| {
                text.replace(key, value)
            })
    };
    c.push_str(&render(include_str!("header.h.in")));
    let r = render(include_str!("binding.rs.in"));
    let dll = render(include_str!("library.rs.in"));
    Ok((c, r, dll))
}

/// 编译算法 DLL 的机器码、CPU/GPU 映像、执行框架静态库与 C/Rust 接口。
pub fn compile_object(program: &ExecutableProgram, prefix: &str) -> Result<crate::object::Object> {
    let prefix = identifier(prefix)?;
    let (header, binding, source) = generate(program, &prefix)?;
    let exports = ["create", "run", "destroy"]
        .into_iter()
        .map(|n| format!("{prefix}_{n}"))
        .collect();
    let archive = crate::object::compile_archive(&source, &prefix, exports)?;
    Ok(crate::object::Object {
        name: program.name().into(),
        kind: crate::object::Kind::Library {
            prefix,
            header,
            binding,
        },
        sections: Vec::new(),
        archive: Some(archive),
    })
}
/// SDK 现有构建 API 组合正式编译与链接；C/C++ 和 Rust 的 DLL ABI 保持。
pub fn build(program: &ExecutableProgram, output: &Path) -> Result<()> {
    let prefix = output
        .file_stem()
        .and_then(|s| s.to_str())
        .ok_or("缺少 DLL 名称")?;
    crate::linker::link_object(compile_object(program, prefix)?, output)
}
